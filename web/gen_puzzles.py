"""web/gen_puzzles.py - writes web/puzzles.js (the game's 100 boards for the
page's preset list) from src/chuzzles/levels_cells.hpp and levels.hpp, with
each puzzle's known optimum (build/levels_final) or lower bound (build/README.md).

    python web/gen_puzzles.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    cells_src = re.sub(r"//[^\n]*", "", (ROOT / "src/chuzzles/levels_cells.hpp").read_text())
    cells = {m.group(1): [int(v) for v in re.findall(r"\d+", m.group(2))]
             for m in re.finditer(r"INIT\s+(\w+)\s*\[36\]\s*=\s*\{([^}]*)\}", cells_src)}

    defs_src = re.sub(r"//[^\n]*", "", (ROOT / "src/chuzzles/levels.hpp").read_text())
    fat_re = r"\{\s*(?:true\s*,\s*(\d)\s*,\s*(\d))?\s*\}"
    defs = re.finditer(r'\{"(\d+-\d)",\s*LevelCells::(\w+),\s*LevelCells::(\w+),\s*' + fat_re + r",\s*" + fat_re,
                       defs_src)

    optimum = {}
    for f in (ROOT / "build/levels_final").glob("*_c*_*.txt"):
        m = re.match(r"(\d+-\d)_c(\d+)_(\d+)\.txt$", f.name)
        if m and (m.group(1) not in optimum or int(m.group(2)) < optimum[m.group(1)][0]):
            optimum[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    bounds = {m.group(1): int(m.group(2)) for m in
              re.finditer(r"^(\d+-\d): at least (\d+) moves", (ROOT / "build/README.md").read_text(), re.M)}

    puzzles = []
    for d in defs:
        name, b, s, sx, sy, gx, gy = d.groups()
        if int(name.split("-")[0]) > 20:      # levels.hpp's extra test boards, not the game's
            continue
        p = {"name": name, "start": cells[b], "goal": cells[s]}
        if sx is not None:
            # levels.hpp gives (x = column, y = row) of the piece's top-left cell
            p["fat"] = {"start": [int(sx), int(sy)], "goal": [int(gx), int(gy)]}
        if name in optimum:
            p["moves"], p["solutions"] = optimum[name]
        elif name in bounds:
            p["atLeast"] = bounds[name]
        puzzles.append(p)
    puzzles.sort(key=lambda p: [int(x) for x in p["name"].split("-")])

    out = ("// web/puzzles.js - generated by web/gen_puzzles.py; do not edit.\n"
           "// The game's boards: start / goal colours row-major (0 red, 1 green, 2 blue, 3 orange,\n"
           "// 4 yellow, 5 purple, 6 white, 7 cyan), fat = the 2x2 piece's [column, row].\n"
           "self.MB_PUZZLES = [\n"
           + ",\n".join("  " + json.dumps(p, separators=(",", ":")) for p in puzzles)
           + "\n];\n")
    (ROOT / "web/puzzles.js").write_text(out, newline="\n")
    print(f"wrote web/puzzles.js ({len(puzzles)} puzzles)")


if __name__ == "__main__":
    main()
